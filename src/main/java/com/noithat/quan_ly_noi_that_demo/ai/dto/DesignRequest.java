package com.noithat.quan_ly_noi_that_demo.ai.dto;

public class DesignRequest {

    private String loaiPhong;
    private Double dienTich;
    private Double nganSach;
    private String phongCach;
    private String mauSac;
    private String yeuCau;

    public String getLoaiPhong() {
        return loaiPhong;
    }

    public void setLoaiPhong(String loaiPhong) {
        this.loaiPhong = loaiPhong;
    }

    public Double getDienTich() {
        return dienTich;
    }

    public void setDienTich(Double dienTich) {
        this.dienTich = dienTich;
    }

    public Double getNganSach() {
        return nganSach;
    }

    public void setNganSach(Double nganSach) {
        this.nganSach = nganSach;
    }

    public String getPhongCach() {
        return phongCach;
    }

    public void setPhongCach(String phongCach) {
        this.phongCach = phongCach;
    }

    public String getMauSac() {
        return mauSac;
    }

    public void setMauSac(String mauSac) {
        this.mauSac = mauSac;
    }

    public String getYeuCau() {
        return yeuCau;
    }

    public void setYeuCau(String yeuCau) {
        this.yeuCau = yeuCau;
    }
}